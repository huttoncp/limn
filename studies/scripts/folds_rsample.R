## folds_rsample: are ilm_folds()'s rolling origins and grouped folds the
## standard ones?
##
## Outside implementation: rsample (not a limn dependency).
##   Rolling origins: rsample::rolling_origin() on a single series, for
##     expanding (cumulative = TRUE) and sliding (cumulative = FALSE) windows
##     and several steps (skip = step - 1). Deterministic, so the training and
##     test rows should be IDENTICAL, fold by fold.
##   Grouped folds: rsample::group_vfold_cv(). The assignment is random in
##     both, so what must agree are the properties: no group split between
##     training and test, every group held out exactly once, and the same
##     balance of groups across folds.
## rsample's `lag` has no counterpart (it overlaps the sets rather than
## separating them), so gaps are not compared here.
##
## Run from the package root: Rscript studies/scripts/folds_rsample.R
suppressPackageStartupMessages({
  pkgload::load_all(".", quiet = TRUE)
  library(rsample)
})
version <- as.character(utils::packageVersion("limn"))
out_dir <- file.path("studies", "runs", version, "folds_rsample")
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)

## ---- rolling origins -----------------------------------------------------------
rows <- list()
for (n in c(24L, 61L)) for (initial in c(5L, 12L)) for (assess in c(1L, 3L))
  for (step in c(1L, 2L, 5L)) for (cumulative in c(TRUE, FALSE)) {
    d <- data.frame(t = seq_len(n), y = rnorm(n))
    rs <- rolling_origin(d, initial = initial, assess = assess,
                         cumulative = cumulative, skip = step - 1L)
    lf <- ilm_folds(d, "rolling", time = "t", initial = initial, horizon = assess,
                    step = step, window = if (cumulative) "expanding" else "sliding")
    same_count <- length(lf) == nrow(rs)
    same_rows <- same_count && all(vapply(seq_along(lf), function(k) {
      sp <- rs$splits[[k]]
      identical(sort(lf[[k]]$train), sort(as.integer(sp, data = "analysis"))) &&
        identical(sort(lf[[k]]$test), sort(as.integer(sp, data = "assessment")))
    }, TRUE))
    rows[[length(rows) + 1L]] <- data.frame(
      n = n, initial = initial, horizon = assess, step = step,
      window = if (cumulative) "expanding" else "sliding",
      folds_limn = length(lf), folds_rsample = nrow(rs),
      identical = same_rows)
  }
roll <- do.call(rbind, rows)

## ---- grouped folds ---------------------------------------------------------------
grp <- list()
for (G in c(10L, 23L, 50L)) for (K in c(3L, 5L, 10L)) for (rep in 1:20) {
  per <- sample(2:9, G, replace = TRUE)            # unequal group sizes
  d <- data.frame(site = rep(sprintf("g%02d", seq_len(G)), per))
  d$y <- rnorm(nrow(d))
  lf <- ilm_folds(d, "grouped", K = K, group = "site", seed = rep)
  set.seed(rep)
  rs <- group_vfold_cv(d, group = site, v = K)
  props <- function(tests) {
    held <- lapply(tests, function(ix) unique(d$site[ix]))
    c(split_groups = sum(vapply(seq_along(tests), function(k)
        length(intersect(unique(d$site[tests[[k]]]),
                         unique(d$site[-tests[[k]]]))), 0L)),
      held_once = as.integer(length(unlist(held)) == G && setequal(unlist(held), d$site)),
      min_groups = min(lengths(held)), max_groups = max(lengths(held)))
  }
  pl <- props(lapply(lf, `[[`, "test"))
  pr <- props(lapply(rs$splits, function(sp) as.integer(sp, data = "assessment")))
  grp[[length(grp) + 1L]] <- data.frame(G = G, K = K, rep = rep,
    t(setNames(pl, paste0("limn_", names(pl)))),
    t(setNames(pr, paste0("rsample_", names(pr)))))
}
grp <- do.call(rbind, grp)
gsum <- aggregate(cbind(limn_split_groups, rsample_split_groups, limn_held_once,
                        rsample_held_once, limn_min_groups, limn_max_groups,
                        rsample_min_groups, rsample_max_groups) ~ G + K,
                  data = grp, FUN = function(v) c(min = min(v), max = max(v)))
gsum <- do.call(data.frame, gsum)

write.csv(roll, file.path(out_dir, "rolling.csv"), row.names = FALSE)
write.csv(gsum, file.path(out_dir, "grouped.csv"), row.names = FALSE)
writeLines(c(paste("Version:", version), paste("Date:", format(Sys.Date())),
             paste("R:", R.version.string),
             paste("rsample:", as.character(utils::packageVersion("rsample")))),
           file.path("studies", "runs", version, "RUNINFO.dcf"))

## ---- findings (generated) ----------------------------------------------------
md <- c(
  "# Folds against rsample", "",
  sprintf("## limn %s (%s; rsample %s)", version, format(Sys.Date()),
          utils::packageVersion("rsample")), "",
  "Generated by `studies/scripts/folds_rsample.R`. Do not edit by hand.", "",
  "**Rolling origins against `rsample::rolling_origin()`.**",
  sprintf("%d configurations: series of 24 and 61, first windows of 5 and 12, horizons of 1 and 3, steps of 1, 2 and 5, expanding and sliding windows.",
          nrow(roll)),
  sprintf("- The same number of folds in %d of %d.", sum(roll$folds_limn == roll$folds_rsample), nrow(roll)),
  sprintf("- Identical training and test rows, fold by fold, in %d of %d.", sum(roll$identical), nrow(roll)), "",
  "**Grouped folds against `rsample::group_vfold_cv()`.**",
  sprintf("20 random datasets for each of %d settings (10, 23 and 50 groups of unequal size; 3, 5 and 10 folds).",
          nrow(gsum)),
  sprintf("- A group split between training and test: never in limn (max %d), never in rsample (max %d).",
          max(grp$limn_split_groups), max(grp$rsample_split_groups)),
  sprintf("- Every group held out exactly once: limn %d of %d, rsample %d of %d.",
          sum(grp$limn_held_once), nrow(grp), sum(grp$rsample_held_once), nrow(grp)),
  sprintf("- Groups per fold differ by at most one: limn %d of %d, rsample %d of %d.",
          sum(grp$limn_max_groups - grp$limn_min_groups <= 1), nrow(grp),
          sum(grp$rsample_max_groups - grp$rsample_min_groups <= 1), nrow(grp)), "",
  "The per-configuration tables are in `studies/runs/<version>/folds_rsample/`.")
writeLines(md, file.path("studies", "findings", "folds_rsample.md"))
cat(md, sep = "\n")
