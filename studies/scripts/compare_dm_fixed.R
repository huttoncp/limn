## compare_dm_fixed: do fixed-smoothing versions of the Diebold-Mariano test
## hold their size with few origins, where the usual one does not? (the
## correction of Coroneo and Iacone 2020)
##
## The design of compare_dm_pooled.R: an AR(1) series (rho 0.6) forecast 1 to H
## steps ahead from each of T origins by two forecasters who add noise of SD
## 0.5 to the optimal forecast, independently over origins or persisting
## (AR(1), phi 0.5). With equal noise every rejection is a false one; with the
## second forecaster's noise larger, rejections measure power. Losses: squared
## and absolute errors.
##
## Three tests of the per-origin mean loss differences, pooled over horizons
## and at single horizons:
##   DM-HLN: the current test of ilm_compare(by = "origin"), a truncated
##           long-run variance to lag (horizon - 1), Harvey, Leybourne and
##           Newbold's factor, and t on T - 1 degrees of freedom;
##   WCE:    Bartlett weights to M = floor(T^(1/2)), with Kiefer and
##           Vogelsang's fixed-b critical values;
##   WPE:    the Daniell periodogram at m = floor(T^(1/3)) frequencies, with t
##           on 2m degrees of freedom.
## Rejection rates at 5% and 10%; at R = 1000 a 5% rate's Monte Carlo SE is
## 0.007.
##
## Run from the package root: Rscript studies/scripts/compare_dm_fixed.R [R] [cores]
args <- commandArgs(TRUE)
R <- if (length(args) >= 1) as.integer(args[1]) else 1000L
cores <- if (length(args) >= 2) as.integer(args[2]) else 4L
suppressPackageStartupMessages(pkgload::load_all(".", quiet = TRUE))
version <- as.character(utils::packageVersion("limn"))
out_dir <- file.path("studies", "runs", version, "compare_dm_fixed")
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)

losses <- function(Tn, H, tau_a, tau_b, phi, power, rho = 0.6) {
  n <- Tn + H + 50L
  y <- as.numeric(stats::arima.sim(list(ar = rho), n))[51:n]
  noise <- function(tau) {
    z <- matrix(stats::rnorm(Tn * H, 0, tau), Tn, H)
    if (phi > 0) for (o in 2:Tn) z[o, ] <- phi * z[o - 1, ] + sqrt(1 - phi^2) * z[o, ]
    z
  }
  a <- noise(tau_a); b <- noise(tau_b)
  e <- outer(seq_len(Tn), seq_len(H), function(o, h) y[o + h] - rho^h * y[o])
  abs(e - b)^power - abs(e - a)^power                # T x H loss differences
}
## the three tests' rejections at 5% and 10% for one series of origin means
reject <- function(dt, lag) {
  dm <- suppressWarnings(lmn_se_dm(dt, seq_along(dt), lag))
  wce <- lmn_dm_wce(dt); wpe <- lmn_dm_wpe(dt)
  c(dm_05 = dm$p < 0.05, dm_10 = dm$p < 0.10,
    wce_05 = abs(wce$statistic) > wce$cv[["0.05"]], wce_10 = abs(wce$statistic) > wce$cv[["0.10"]],
    wpe_05 = wpe$p < 0.05, wpe_10 = wpe$p < 0.10)
}

cells <- rbind(
  expand.grid(H = c(1L, 4L), Tn = c(10L, 20L, 50L, 100L, 200L), power = 1:2, phi = c(0, 0.5),
              ratio = 1, stringsAsFactors = FALSE),
  expand.grid(H = 4L, Tn = c(20L, 50L, 200L), power = 2L, phi = 0, ratio = c(1.25, 1.5),
              stringsAsFactors = FALSE))
run_cell <- function(k, cells, R, losses, reject) {
  set.seed(20260927 + k)
  ce <- cells[k, ]
  sims <- replicate(R, {
    D <- losses(ce$Tn, ce$H, 0.5, 0.5 * ce$ratio, ce$phi, ce$power)
    c(pooled = reject(rowMeans(D), ce$H - 1L), first = reject(D[, 1], 0L),
      last = reject(D[, ce$H], ce$H - 1L))
  })
  cbind(ce, as.data.frame(t(rowMeans(sims))), R = R)
}
t0 <- Sys.time()
cl <- parallel::makePSOCKcluster(cores)
invisible(parallel::clusterCall(cl, function(p) pkgload::load_all(p, quiet = TRUE), normalizePath(".")))
res <- do.call(rbind, parallel::parLapplyLB(cl, seq_len(nrow(cells)), run_cell, cells = cells, R = R,
                                            losses = losses, reject = reject))
parallel::stopCluster(cl)
minutes <- as.numeric(difftime(Sys.time(), t0, units = "mins"))
write.csv(res, file.path(out_dir, "rejections.csv"), row.names = FALSE)

f3 <- function(v) sprintf("%.3f", v)
lab <- function(s) paste(ifelse(s$power == 2, "squared", "absolute"), ifelse(s$phi > 0, "persistent", "independent"), sep = ", ")
nul <- res[res$ratio == 1, ]; pw <- res[res$ratio > 1, ]
tab <- function(what, head) {
  c(head, "",
    "| H | T | loss, noise | DM-HLN | WCE | WPE |", "|---|---|---|---|---|---|",
    sprintf("| %d | %d | %s | %s | %s | %s |", nul$H, nul$Tn, lab(nul),
            f3(nul[[paste0(what, ".dm_05")]]), f3(nul[[paste0(what, ".wce_05")]]),
            f3(nul[[paste0(what, ".wpe_05")]])), "")
}
worst <- function(m, what = "pooled") {
  v <- nul[[paste0(what, ".", m, "_05")]]
  sprintf("%s to %s", f3(min(v)), f3(max(v)))
}
