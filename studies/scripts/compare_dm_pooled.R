## compare_dm_pooled: does the pooled test of ilm_compare(by = "origin") hold
## its size, and what is its power?
##
## ilm_compare(by = "origin") averages each origin's loss differences over its
## horizons, then tests the origin means with the Diebold-Mariano statistic, a
## long-run variance to lag (longest horizon - 1) and the Harvey-Leybourne-
## Newbold factor at that horizon: the average multi-horizon comparison of
## Quaedvlieg (2021). compare_dm.R checked the single-horizon case against
## forecast::dm.test(). This checks the pooled case by simulation, since no
## outside implementation of it is at hand.
##
## An AR(1) series (rho 0.6) is forecast 1 to H steps ahead from each of T
## origins, so neighbouring origins' errors overlap. Two forecasters add noise
## of SD tau to the optimal forecast, independently at each origin and
## horizon, or persisting across origins (AR(1), phi 0.5). With equal tau their
## expected losses are equal exactly, by symmetry, so every rejection is a false
## one; the rejection rate at 5% should be 0.05, within 0.014 (two Monte Carlo
## SEs at R = 1000). With the second forecaster's tau larger, rejections
## measure power. Losses: squared and absolute errors. Per-horizon tests (one
## horizon's rows, the validated case) are given beside the pooled test.
##
## Run from the package root: Rscript studies/scripts/compare_dm_pooled.R [R] [cores]
args <- commandArgs(TRUE)
R <- if (length(args) >= 1) as.integer(args[1]) else 1000L
cores <- if (length(args) >= 2) as.integer(args[2]) else 6L
suppressPackageStartupMessages(pkgload::load_all(".", quiet = TRUE))
version <- as.character(utils::packageVersion("limn"))
out_dir <- file.path("studies", "runs", version, "compare_dm_pooled")
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)

## one replicate: the two forecasters' losses at every origin and horizon
losses <- function(Tn, H, tau_a, tau_b, phi, power, rho = 0.6) {
  n <- Tn + H + 50L
  y <- as.numeric(stats::arima.sim(list(ar = rho), n))[51:n]         # Tn + H values
  noise <- function(tau) {                                           # T x H, AR(1) over origins
    z <- matrix(stats::rnorm(Tn * H, 0, tau), Tn, H)
    if (phi > 0) for (o in 2:Tn) z[o, ] <- phi * z[o - 1, ] + sqrt(1 - phi^2) * z[o, ]
    z
  }
  a <- noise(tau_a); b <- noise(tau_b)
  e <- outer(seq_len(Tn), seq_len(H), function(o, h) y[o + h] - rho^h * y[o])
  data.frame(origin = rep(seq_len(Tn), H), horizon = rep(seq_len(H), each = Tn),
             la = as.vector(abs(e - a)^power), lb = as.vector(abs(e - b)^power))
}
test_p <- function(d, h = NULL) {
  if (!is.null(h)) d <- d[d$horizon == h, ]
  r <- suppressWarnings(ilm_compare(A = data.frame(origin = d$origin, horizon = d$horizon, loss = d$la),
                                    B = data.frame(origin = d$origin, horizon = d$horizon, loss = d$lb),
                                    rule = "loss", by = "origin", method = "dm"))[1, ]
  c(p = r$p_value, fell_back = grepl("lag 0", r$method) && max(d$horizon) > 1)
}

cells <- rbind(
  expand.grid(H = c(1L, 2L, 4L), Tn = c(20L, 50L, 100L, 200L), power = 1:2, phi = c(0, 0.5),
              ratio = 1, stringsAsFactors = FALSE),
  expand.grid(H = 4L, Tn = c(50L, 200L), power = 2L, phi = 0, ratio = c(1.25, 1.5),
              stringsAsFactors = FALSE))
t0 <- Sys.time()
run_cell <- function(k, cells, R, losses, test_p) {
  set.seed(20260926 + k)
  ce <- cells[k, ]
  sims <- replicate(R, {
    d <- losses(ce$Tn, ce$H, 0.5, 0.5 * ce$ratio, ce$phi, ce$power)
    pooled <- test_p(d)
    per_h <- vapply(seq_len(ce$H), function(h) test_p(d, h)[["p"]], 0)
    c(pooled, per_h_any = any(per_h < 0.05), per_h_first = per_h[1], per_h_last = per_h[ce$H])
  })
  data.frame(ce, rejected = mean(sims["p", ] < 0.05), rejected_10 = mean(sims["p", ] < 0.10),
             fell_back = mean(sims["fell_back", ]),
             per_h1_rejected = mean(sims["per_h_first", ] < 0.05),
             per_hH_rejected = mean(sims["per_h_last", ] < 0.05), R = R)
}
cl <- parallel::makePSOCKcluster(cores)
invisible(parallel::clusterCall(cl, function(p) pkgload::load_all(p, quiet = TRUE), normalizePath(".")))
res <- do.call(rbind, parallel::parLapplyLB(cl, seq_len(nrow(cells)), run_cell, cells = cells, R = R,
                                            losses = losses, test_p = test_p))
parallel::stopCluster(cl)
minutes <- as.numeric(difftime(Sys.time(), t0, units = "mins"))
res$mc_se <- sqrt(res$rejected * (1 - res$rejected) / R)
print(res)
write.csv(res, file.path(out_dir, "rejections.csv"), row.names = FALSE)

nul <- res[res$ratio == 1, ]; pw <- res[res$ratio > 1, ]
off <- nul[abs(nul$rejected - 0.05) > 0.014, ]
f3 <- function(v) sprintf("%.3f", v)
md <- c(
