  sprintf("## limn %s (%s)", version, format(Sys.Date())), "",
  "Generated by `studies/scripts/compare_dm_pooled.R`. Do not edit by hand.", "",
  sprintf(paste("An AR(1) series forecast 1 to H steps ahead from T origins by two forecasters whose noise",
                "(SD 0.5) is independent over origins or persists (phi 0.5). %d replicates per cell (Monte",
                "Carlo SE of a 5%% rejection rate: 0.007), %.1f minutes on %d cores."), R, minutes, cores), "",
  "**Size** (equal forecasters): the rejection rate at 5% of the pooled test, and of the tests at the first and the last horizon alone:", "",
  "| H | T | loss | noise over origins | pooled | h = 1 alone | h = H alone | fell back to lag 0 |",
  "|---|---|---|---|---|---|---|---|",
  sprintf("| %d | %d | %s | %s | %s | %s | %s | %s |", nul$H, nul$Tn,
          ifelse(nul$power == 2, "squared", "absolute"), ifelse(nul$phi > 0, "persistent", "independent"),
          f3(nul$rejected), f3(nul$per_h1_rejected), f3(nul$per_hH_rejected), f3(nul$fell_back)), "",
  sprintf("Cells whose pooled size is outside 0.05 +/- 0.014: %s.",
          if (nrow(off)) paste(sprintf("H = %d, T = %d, %s, %s: %s", off$H, off$Tn,
                                       ifelse(off$power == 2, "squared", "absolute"),
                                       ifelse(off$phi > 0, "persistent", "independent"),
                                       f3(off$rejected)), collapse = "; ") else "none"), "",
  "**Power** (the second forecaster's noise SD larger by the ratio shown; squared loss, H = 4):", "",
  "| T | ratio | pooled | h = 1 alone | h = 4 alone |", "|---|---|---|---|---|",
  sprintf("| %d | %.2f | %s | %s | %s |", pw$Tn, pw$ratio, f3(pw$rejected), f3(pw$per_h1_rejected),
          f3(pw$per_hH_rejected)))
writeLines(md, file.path("studies", "findings", "compare_dm_pooled.md"))
cat(md, sep = "\n")
