## compare_dm: does ilm_compare(by = "origin") give the Diebold-Mariano test?
##
## Outside implementation: forecast::dm.test() (not a limn dependency), with
## its default variance estimator (autocovariances to lag h - 1) and the
## Harvey-Leybourne-Newbold correction. Two forecasters' h-step errors are
## simulated as MA(h - 1) processes, so neighbouring origins really are
## correlated, and scored by |e|^power. ilm_compare() gets one row per origin
## at horizon h, so its default lag is h - 1, and it should return the same
## statistic and p-value.
##
## Run from the package root: Rscript studies/scripts/compare_dm.R
suppressPackageStartupMessages({
  pkgload::load_all(".", quiet = TRUE)
  library(forecast)
})
version <- as.character(utils::packageVersion("limn"))
out_dir <- file.path("studies", "runs", version, "compare_dm")
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)

ma_errors <- function(Tn, h, sd) {
  z <- rnorm(Tn + h - 1L, 0, sd)
  as.numeric(stats::filter(z, rep(1, h), sides = 1))[h:(Tn + h - 1L)]
}
set.seed(20260924)
rows <- list()
for (Tn in c(20L, 60L, 200L)) for (h in 1:4) for (power in 1:2) for (rep in 1:25) {
  e1 <- ma_errors(Tn, h, 1)
  e2 <- 0.8 * e1 + ma_errors(Tn, h, 0.7)            # correlated competitors
  dm <- suppressWarnings(dm.test(e1, e2, h = h, power = power))
  a <- data.frame(origin = seq_len(Tn), horizon = h, loss = abs(e2)^power)
  b <- data.frame(origin = seq_len(Tn), horizon = h, loss = abs(e1)^power)
  lc <- suppressWarnings(ilm_compare(ref = a, mod = b, rule = "loss", by = "origin",
                                     method = "dm"))
  rows[[length(rows) + 1L]] <- data.frame(
    T = Tn, h = h, power = power, rep = rep,
    stat_dm = unname(dm$statistic), stat_limn = lc$statistic,
    p_dm = dm$p.value, p_limn = lc$p_value,
    fell_back = grepl("lag 0", lc$method) && h > 1)
}
res <- do.call(rbind, rows)
res$stat_diff <- abs(res$stat_limn - res$stat_dm)
res$p_diff <- abs(res$p_limn - res$p_dm)
cells <- aggregate(cbind(stat_diff, p_diff, fell_back) ~ T + h + power, data = res,
                   FUN = max)
write.csv(cells, file.path(out_dir, "cells.csv"), row.names = FALSE)

md <- c(
  "# ilm_compare(by = \"origin\") against forecast::dm.test()", "",
  sprintf("## limn %s (%s; forecast %s)", version, format(Sys.Date()),
          utils::packageVersion("forecast")), "",
  "Generated by `studies/scripts/compare_dm.R`. Do not edit by hand.", "",
  sprintf("%d comparisons: %d series lengths (20, 60, 200 origins) x horizons 1-4 x powers 1 and 2 x 25 replicates, with MA(h - 1) errors so that neighbouring origins are correlated.",
          nrow(res), 3L),
  "",
  sprintf("- Largest difference in the statistic: %.1e.", max(res$stat_diff)),
  sprintf("- Largest difference in the p-value: %.1e.", max(res$p_diff)),
  sprintf("- The long-run variance was not positive, so both fell back to lag 0, in %d comparisons.",
          sum(res$fell_back)), "",
  "The per-cell maxima are in `studies/runs/<version>/compare_dm/cells.csv`.")
writeLines(md, file.path("studies", "findings", "compare_dm.md"))
cat(md, sep = "\n")
