## compare_dm_negative: ilm_compare(method = "dm") against Harvey, Leybourne and
## Newbold (1997), Table 1, and how often Diebold and Mariano's rule for a
## negative variance is called on.
##
## The design is HLN's (p. 284): independent N(0, 1) errors e1 and e2 of length
## n, squared-error loss d = e1^2 - e2^2, horizon h with truncation lag h - 1,
## a two-sided test at nominal 10%, 10,000 replications per cell. Their Table 1
## (p. 285) gives, as the fourth row of each h block, the size of the modified
## test: their statistic (9) with t(n - 1) critical values. limn's method = "dm"
## is that test, with Diebold and Mariano's (1995, section 1.1) rule for a
## negative long-run variance: taken as 0, and the null rejected. HLN do not say
## how their simulations treated a negative estimate.
##
## Run from the package root: Rscript studies/scripts/compare_dm_negative.R
suppressPackageStartupMessages(pkgload::load_all(".", quiet = TRUE))
version <- as.character(utils::packageVersion("limn"))
out_dir <- file.path("studies", "runs", version, "compare_dm_negative")
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)

R <- 10000L
## HLN Table 1 (p. 285), the fourth row of each h block (modified test, t(n - 1))
table1 <- list(`1` = c(`8` = 8.4, `16` = 9.6, `32` = 9.7, `64` = 10.1, `128` = 9.9),
               `2` = c(`8` = 16.4, `16` = 14.2, `32` = 12.2, `64` = 11.2, `128` = 10.8),
               `3` = c(`8` = 18.1, `16` = 18.5, `32` = 14.3, `64` = 12.2, `128` = 10.7),
               `5` = c(`8` = 12.9, `16` = 19.9, `32` = 17.8, `64` = 14.9, `128` = 12.2))
set.seed(20261013)
rows <- list()
for (h in names(table1)) for (n in names(table1[[h]])) {
  hh <- as.integer(h); nn <- as.integer(n)
  rej <- neg <- logical(R)
  for (r in seq_len(R)) {
    d <- stats::rnorm(nn)^2 - stats::rnorm(nn)^2
    res <- withCallingHandlers(lmn_se_dm(d, seq_len(nn), hh - 1L),
                               lmn_dm_negative_variance = function(w) {
                                 neg[r] <<- TRUE; invokeRestart("muffleWarning") })
    rej[r] <- isTRUE(res$p < 0.10)
  }
  size <- 100 * mean(rej)
  se <- 100 * sqrt(mean(rej) * (1 - mean(rej)) / R)
  rows[[length(rows) + 1L]] <- data.frame(
    h = hh, n = nn, table1 = table1[[h]][[n]], rejections = sum(rej), limn = size, mc_se = se,
    ## both percentages come from 10,000 replications, so the difference has about
    ## sqrt(2) times limn's standard error
    z = (size - table1[[h]][[n]]) / (sqrt(2) * se),
    negative = sum(neg), negative_pct = 100 * mean(neg))
}
cells <- do.call(rbind, rows)
write.csv(cells, file.path(out_dir, "cells.csv"), row.names = FALSE)

rare <- cells$negative_pct < 0.5
fmt <- function(x, d = 2) formatC(x, format = "f", digits = d)
tab <- c("| h | n | Table 1 (%) | limn (%) | MC SE | z | negative variance (%) |",
         "|---|---|---|---|---|---|---|",
         sprintf("| %d | %d | %s | %s | %s | %s | %s |", cells$h, cells$n, fmt(cells$table1, 1),
                 fmt(cells$limn), fmt(cells$mc_se), fmt(cells$z), fmt(cells$negative_pct)))
worst <- cells[which.max(cells$limn - cells$table1), ]
md <- c(
  "# ilm_compare(method = \"dm\") against Harvey, Leybourne and Newbold (1997), Table 1", "",
  sprintf("## limn %s (%s)", version, format(Sys.Date())), "",
  "Generated by `studies/scripts/compare_dm_negative.R`. Do not edit by hand.", "",
  paste("The design is Harvey, Leybourne and Newbold's (1997, p. 284): independent N(0, 1) errors,",
        "d = e1^2 - e2^2, horizon h with truncation lag h - 1, a two-sided test at nominal 10%,",
        sprintf("%s replications per cell, seed 20261013.", format(R, big.mark = ","))),
  paste("Table 1 is their Table 1 (p. 285), the fourth row of each h block: the modified test,",
        "their statistic (9) with t(n - 1) critical values. limn's method = \"dm\" is that test, with",
        "Diebold and Mariano's (1995, section 1.1) rule for a negative long-run variance: taken as",
        "0, and the null rejected. Harvey, Leybourne and Newbold do not say how their simulations",
        "treated a negative estimate."), "",
  tab, "",
  sprintf(paste("- In the %d cells where a negative variance arose in under 0.5%% of samples, limn's",
                "size is within %s standard errors of the difference from Table 1 (largest |z|)."),
          sum(rare), fmt(max(abs(cells$z[rare])))),
  sprintf(paste("- Where a negative variance is common, Diebold and Mariano's rule raises the size",
                "well above Table 1: at h = %d, n = %d, a negative variance arose in %s%% of",
                "samples, and the size was %s%% against Table 1's %s%%."),
          worst$h, worst$n, fmt(worst$negative_pct), fmt(worst$limn), fmt(worst$table1, 1)),
  "", "The per-cell results are in `studies/runs/<version>/compare_dm_negative/cells.csv`.")
writeLines(md, file.path("studies", "findings", "compare_dm_negative.md"))
cat(md, sep = "\n")
cat("\nSTUDY DONE\n")
